import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it, vi } from "vitest";
import { MockBackend } from "./backend/mock";
import { BotLibraryProvider } from "./BotLibrary";
import { CustomBotStudio } from "./CustomBotStudio";

it("requires separate preview and pose approval, reuses the preview, and assigns the saved bot", async () => {
  Object.defineProperty(HTMLDialogElement.prototype, "showModal", { configurable: true, value: function (this: HTMLDialogElement) { this.open = true; } });
  Object.defineProperty(HTMLDialogElement.prototype, "close", { configurable: true, value: function (this: HTMLDialogElement) { this.open = false; } });
  const backend = new MockBackend();
  await backend.saveApiKey("test-key");
  const originalGenerate = backend.generateBotImage.bind(backend);
  const generate = vi.spyOn(backend, "generateBotImage").mockImplementationOnce(async request => ({ ...await originalGenerate(request), transparentPoses: [], backgroundRemovalError: "Local cleanup was interrupted." }));
  const cleanup = vi.spyOn(backend, "removeBotBackgrounds");
  const useBot = vi.fn(), close = vi.fn();
  render(<BotLibraryProvider backend={backend}><CustomBotStudio backend={backend} status={await backend.modelAccess()} currentSeed="test" title="Daily calendar summary" useBot={useBot} close={close} openSettings={() => {}} /></BotLibraryProvider>);
  await waitFor(() => expect(screen.getByLabelText("Describe your character")).toBeEnabled());
  expect(screen.getByLabelText("Describe your character")).toHaveValue("Daily calendar summary");
  fireEvent.change(screen.getByLabelText("Describe your character"), { target: { value: "A sleepy fox with tiny ears and warm orange coloring" } });
  const preview = screen.getByRole("button", { name: "Generate preview · US$0.01" });
  expect(preview).toBeDisabled();
  const user = userEvent.setup();
  await user.click(screen.getByLabelText("I approve the preview request and estimated US$0.01 charge."));
  await user.click(preview);
  await screen.findByAltText("Preview pose");
  expect(screen.getByRole("region", { name: "Your character preview" })).toContainElement(screen.getByAltText("Preview pose"));
  expect(screen.getByRole("heading", { name: "Your character preview" })).toHaveFocus();
  expect(generate).toHaveBeenCalledTimes(1);
  expect(generate.mock.calls[0][0].description).toBe("A sleepy fox with tiny ears and warm orange coloring");
  expect(screen.getByRole("button", { name: "Use preview for now" })).toBeDisabled();
  await user.click(screen.getByRole("button", { name: "Remove backgrounds · no API charge" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Use preview for now" })).toBeEnabled());
  expect(cleanup).toHaveBeenCalledOnce();
  expect(generate).toHaveBeenCalledTimes(1);
  const poses = screen.getByRole("button", { name: "Generate 5 poses · US$0.05" });
  expect(poses).toBeDisabled();
  await user.click(screen.getByLabelText("I approve sending this preview to Meta and the estimated US$0.05 charge."));
  await user.click(poses);
  await user.click(await screen.findByRole("button", { name: "Use this character" }));
  expect(generate.mock.calls.map(([request]) => request.pose)).toEqual([0, 1, 2, 3, 4, 5]);
  expect(new Set(generate.mock.calls.map(([request]) => request.id)).size).toBe(1);
  expect(useBot).toHaveBeenCalledWith(expect.stringMatching(/^custom:/));
  expect(close).toHaveBeenCalledOnce();
});
